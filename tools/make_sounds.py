def fetch():
    FS.mkdir(parents=True, exist_ok=True)
    for i, (path, title) in FREESOUND.items():
        dst = FS / f"{i}.mp3"
        if not dst.exists() or dst.stat().st_size < 1000:
            run(["curl", "-sf", "-o", str(dst), "https://cdn.freesound.org/previews/" + path])
            print("fetched", i, title)


