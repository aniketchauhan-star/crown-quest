#!/usr/bin/env python3
"""Makes the game's recorded sound effects from the recordings in art/audio/ (needs ffmpeg).
(art/ was taken out of the folder on 2026-11-13 to keep it small: bring it back first, README.md,
"Replace the artwork".)

- art/audio/snore.mp3 -> assets/audio/grumble-snore-1.mp3 ... (one file per snore): the recording is
  cut on its silences into its snores, each a snore in, a pause and a snore out, and each is levelled
  to -20 LUFS (under the voice). It prints each snore's timing: paste the list into `snores` in the
  `audio` section of js/content.js (Grumble's breathing follows each sound: js/world.js, sleep).
- art/audio/monkey laugh.mp3 -> assets/audio/zippy-win-laugh.mp3: Zippy's laugh when he wins a crown,
  short (reviews of 2026-11-13 and 2026-11-18: "reduce the timing of Zippy's laugh"): its first loud
  "ha"s, from 0.55 s (after the quiet first ones) to 2.30 s (the clear gap after the eighth "ha"), the
  last one faded out from 2.10 s, 1.75 s in all, levelled to -16 LUFS. (It was 2.77 s, to 3.32 s, and
  before that the first 5.6 s, with the tail of chuckles.) Its length is `winLaugh` in js/content.js.
- art/audio/wood ring.mp3 -> assets/audio/alarm-wood-ring.mp3: the treasure room's alarm when the balance
  tips (a wrong swap, and the intro's "what if" cloud): its one wooden strike, struck twice 0.42 s apart
  (RING! RING!), levelled to -17 LUFS.
- art/audio/confetti pop.ogg + art/audio/confetti rustle.ogg -> assets/audio/confetti.mp3: the shower
  of confetti (a solved practice equation, the last answer of an activity, a crown won), real
  recordings, not made sounds (asked 2026-11-19: "It should not like it's generated by AI. Best SFX"):
  a burst (pop) with the crisp paper of a handful of confetti falling after it (from 0.33 s, where a
  shower starts, low thumps of the hand filtered out, fading away by 1.45 s), levelled to -18 LUFS,
  the pop's crack kept whole (no fade-in, no limiter on it). Both are Freesound CC0 (public domain),
  the "HQ preview" files: https://freesound.org/s/458398/ ("Balloon Pop / Christmas cracker / Confetti
  Cannon", Breviceps) and https://freesound.org/s/416453/ ("Confetti Rustle", KalhanRaina).

- art/audio/monster roar.mp3 -> assets/audio/grumble-roar.mp3: Grumble's roar, a real recording (Freesound
  CC0 https://freesound.org/s/467228/, asked 2026-11-20: "make it too real"): see roar().
- art/audio/monkey little.mp3, monkey low.mp3, gulp.mp3 -> assets/audio/zippy-*.mp3: Zippy's voice sounds
  (giggle, laugh, whee, eek, hmm, catch, gulp), real recordings (asked 2026-11-20): see ZIPPY.

Run from the project folder:  python3 tools/make_sounds.py   (only one: ... make_sounds.py confetti | roar | zippy)
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art" / "audio"
OUT = ROOT / "assets" / "audio"


def run(args):
    return subprocess.run(args, capture_output=True, text=True, check=True)


def loudness(path, start=None, dur=None):
    """Integrated loudness (LUFS) of a file, or of a stretch of it."""
    args = ["ffmpeg", "-hide_banner", "-nostats"]
    if start is not None:
        args += ["-ss", f"{start:.3f}", "-t", f"{dur:.3f}"]
    args += ["-i", str(path), "-af", "ebur128", "-f", "null", "-"]
    out = run(args).stderr
    vals = re.findall(r"I:\s+(-?[\d.]+) LUFS", out)
    return float(vals[-1])


def true_peak(path):
    out = run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-af", "ebur128=peak=true", "-f", "null", "-"]).stderr
    return float(re.findall(r"Peak:\s+(-?[\d.]+) dBFS", out)[-1])


def make(src, dst, start, dur, target, fade_from=None, mono=True, rate=44100):
    """Cut [start, start + dur], level it to `target` LUFS, keep its peaks under -1 dBFS once encoded
    (a clip whose sharp snorts still poke over is made a little quieter), write MP3."""
    gain = target - loudness(src, start, dur)
    for _ in range(3):
        encode(src, dst, start, dur, gain, fade_from, mono, rate)
        over = true_peak(dst) + 1.0
        if over <= 0:
            return
        gain -= over + 0.1


def encode(src, dst, start, dur, gain, fade_from, mono, rate):
    filters = [f"volume={gain:.2f}dB", "alimiter=limit=0.66:level=false", "afade=t=in:d=0.03"]
    if fade_from is not None:
        filters.append(f"afade=t=out:st={fade_from - start:.3f}:d={start + dur - fade_from:.3f}")
    else:
        filters.append(f"afade=t=out:st={max(0.0, dur - 0.08):.3f}:d=0.08")
    args = ["ffmpeg", "-v", "error", "-y", "-ss", f"{start:.3f}", "-t", f"{dur:.3f}", "-i", str(src), "-af", ",".join(filters)]
    args += ["-ac", "1" if mono else "2", "-ar", str(rate), "-c:a", "libmp3lame", "-q:a", "4", str(dst)]
    run(args)


def snores():
    src = SRC / "snore.mp3"
    out = run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(src), "-af", "silencedetect=noise=-42dB:d=0.25", "-f", "null", "-"]).stderr
    total = float(re.search(r"Duration: (\d+):(\d+):([\d.]+)", out).groups()[2]) + 60 * int(re.search(r"Duration: (\d+):(\d+)", out).groups()[1])
    starts = [float(x) for x in re.findall(r"silence_start: ([\d.]+)", out)]
    ends = [float(x) for x in re.findall(r"silence_end: ([\d.]+)", out)]
    # the sounds between the silences: a snore in, then its snore out
    sounds, t = [], 0.0
    for s, e in zip(starts, ends + [total]):
        if s > t + 0.05:
            sounds.append((t, s))
        t = e
    if t < total - 0.05:
        sounds.append((t, total))
    timing = []
    for k in range(0, len(sounds) - 1, 2):
        (a, _), (o, b) = sounds[k], sounds[k + 1]
        start, end = max(0.0, a - 0.05), b + 0.15
        n = k // 2 + 1
        make(src, OUT / f"grumble-snore-{n}.mp3", start, end - start, -20.0, rate=24000)
        timing.append({"cue": f"grumble.snore{n}", "out": round(o - start, 2), "len": round(end - start, 2)})
    return timing


def laugh():
    make(SRC / "monkey laugh.mp3", OUT / "zippy-win-laugh.mp3", 0.55, 1.75, -16.0, fade_from=2.10)


def alarm():
    src = SRC / "wood ring.mp3"
    one = OUT / "_strike.wav"
    two = OUT / "_rings.wav"
    # the strike, from just before it to the end of its ring (the rest of the file is silence)
    run(["ffmpeg", "-v", "error", "-y", "-ss", "0.08", "-t", "0.72", "-i", str(src), "-af", "afade=t=out:st=0.6:d=0.12", "-ac", "1", "-ar", "44100", str(one)])
    # struck twice, 0.42 s apart
    run(["ffmpeg", "-v", "error", "-y", "-i", str(one), "-i", str(one), "-filter_complex", "[1]adelay=420|420[b];[0][b]amix=inputs=2:duration=longest:normalize=0", str(two)])
    make(two, OUT / "alarm-wood-ring.mp3", 0.0, 1.14, -17.0)
    one.unlink()
    two.unlink()


def loudest_moment(path):
    """The loudest 400 ms of a file (momentary loudness, LUFS): how loud a short burst sounds."""
    out = run(["ffmpeg", "-hide_banner", "-nostats", "-v", "verbose", "-i", str(path), "-af", "ebur128=framelog=verbose", "-f", "null", "-"]).stderr
    return max(float(x) for x in re.findall(r" M:\s*(-?[\d.]+)", out))


def confetti(target=-16.5, rustle_db=-7.0):
    """The pop, and 30 ms after it the confetti falling (rustle_db: the paper against the pop), its
    loudest moment at `target` (as loud as the voice at its loudest: a pop's sharp peak would leave a
    sound levelled by its integrated loudness too quiet), peaks under -1 dBFS."""
    pop, rustle = SRC / "confetti pop.ogg", SRC / "confetti rustle.ogg"
    mix, dst = OUT / "_confetti.wav", OUT / "confetti.mp3"
    graph = (
        # the pop (the preview's peaks go over 0 dBFS: kept in floating point, never clipped), only its
        # first sharp spike held down a little, so it can sound as loud as the rest with its crack kept
        "[0]aformat=sample_fmts=fltp:channel_layouts=mono,aresample=44100,volume=-3dB,"
        "alimiter=limit=0.5:attack=0.3:release=40:level=false[p];"
        # the shower: the hand's low thumps out, a soft start, then faded away by its end
        f"[1]aformat=sample_fmts=fltp:channel_layouts=mono,aresample=44100,highpass=f=280:poles=2,volume={rustle_db}dB,"
        "afade=t=in:d=0.012,afade=t=out:st=0.55:d=0.9,adelay=30[r];"
        "[p][r]amix=inputs=2:duration=longest:normalize=0"
    )
    run(["ffmpeg", "-v", "error", "-y", "-i", str(pop), "-ss", "0.33", "-t", "1.45", "-i", str(rustle),
         "-filter_complex", graph, "-c:a", "pcm_f32le", str(mix)])
    gain = target - loudest_moment(mix)
    for _ in range(4):
        run(["ffmpeg", "-v", "error", "-y", "-i", str(mix), "-af", f"volume={gain:.2f}dB",
             "-ac", "1", "-ar", "44100", "-c:a", "libmp3lame", "-q:a", "4", str(dst)])
        over = true_peak(dst) + 1.0
        if over <= 0:
            break
        gain -= over + 0.1
    mix.unlink()


def roar(target=-16.0):
    """Grumble's roar (a wrong swap wakes him; the title's opening; the intro's "what if" cloud): a
    real recorded creature roar, not a made sound (asked 2026-11-20: "The raw [roar] of monster is like
    made by AI… make it too real"). art/audio/monster roar.mp3 is the "HQ preview" of Freesound CC0
    (public domain) https://freesound.org/s/467228/ ("Dragon Roar short", VladimirPetrakov): its first
    roar, from just before it starts (1.28 s) through its loudest stretch, fading out as it dies down
    (2.25–2.75 s), before the second swell: 1.47 s, about as long as he stands roaring (js/world.js,
    wakeUp: 1.1 s with his mouth open). Its loudest moment at `target` (a little over the voice at its
    loudest: it is the scene's big moment), peaks under -1 dBFS."""
    src, dst = SRC / "monster roar.mp3", OUT / "grumble-roar.mp3"
    cut = OUT / "_roar.wav"
    run(["ffmpeg", "-v", "error", "-y", "-ss", "1.28", "-t", "1.47", "-i", str(src), "-af",
         "aformat=sample_fmts=fltp:channel_layouts=mono,aresample=44100,highpass=f=35,"
         "afade=t=in:d=0.01,afade=t=out:st=0.97:d=0.5", "-c:a", "pcm_f32le", str(cut)])
    gain = target - loudest_moment(cut)
    for _ in range(4):
        run(["ffmpeg", "-v", "error", "-y", "-i", str(cut), "-af", f"volume={gain:.2f}dB",
             "-ac", "1", "-ar", "44100", "-c:a", "libmp3lame", "-q:a", "4", str(dst)])
        over = true_peak(dst) + 1.0
        if over <= 0:
            break
        gain -= over + 0.1
    cut.unlink()


# Zippy's voice sounds: real recordings, not made ones (asked 2026-11-20: "Monkey voice is also like this
# generated by AI, so fix this also. It should look natural"). One performer's monkey imitation for all of
# them, so he always sounds like the same little monkey: Freesound CC0 (public domain) "HQ previews" by
# Radio_fragola_gorizia, https://freesound.org/s/400090/ ("littlemonkey", high-pitched: art/audio/
# monkey little.mp3) and https://freesound.org/s/400083/ ("imitating-monkeys", lower: art/audio/monkey
# low.mp3); the gulp is a real swallow, https://freesound.org/s/531755/ ("Gulp - Hard Swallow",
# magnuswaker: art/audio/gulp.mp3). Each is cut to about the length of the made sound it replaces.
# name: (source, start s, length s, fade-out s, loudest moment LUFS, highpass Hz)
ZIPPY = {
    "giggle": ("monkey little.mp3", 11.32, 0.48, 0.08, -19.0, 150),  # three quick "hee"s
    "laugh": ("monkey little.mp3", 11.32, 1.50, 0.25, -18.0, 150),  # eight: the title's laugh
    "whee": ("monkey little.mp3", 14.46, 1.00, 0.12, -17.0, 150),  # three calls, rising: he swings
    "eek": ("monkey little.mp3", 4.13, 0.23, 0.05, -18.5, 150),  # one sharp, high call: scared
    "hmm": ("monkey low.mp3", 3.12, 0.50, 0.06, -21.0, 120),  # two soft "hoo"s: is Grumble asleep?
    "catch": ("monkey low.mp3", 4.30, 0.20, 0.04, -21.0, 120),  # a short "uh!": he catches it
    "gulp": ("gulp.mp3", 0.0, 0.558, 0.05, -19.0, 50),  # a real swallow: uh-oh
}


def zippy(only=None):
    for name, (src, start, dur, fade, target, hp) in ZIPPY.items():
        if only and name != only:
            continue
        cut, dst = OUT / "_zippy.wav", OUT / f"zippy-{name}.mp3"
        run(["ffmpeg", "-v", "error", "-y", "-ss", f"{start:.3f}", "-t", f"{dur:.3f}", "-i", str(SRC / src), "-af",
             f"aformat=sample_fmts=fltp:channel_layouts=mono,aresample=44100,highpass=f={hp},"
             f"afade=t=in:d=0.006,afade=t=out:st={dur - fade:.3f}:d={fade:.3f}", "-c:a", "pcm_f32le", str(cut)])
        # (a call shorter than the meter's 400 ms window is measured with silence after it: its loudness
        # over that window, as a short burst is heard)
        probe = OUT / "_zippy_pad.wav"
        run(["ffmpeg", "-v", "error", "-y", "-i", str(cut), "-af", "apad=whole_dur=0.5", "-c:a", "pcm_f32le", str(probe)])
        gain = target - loudest_moment(probe)
        probe.unlink()
        for _ in range(4):
            run(["ffmpeg", "-v", "error", "-y", "-i", str(cut), "-af", f"volume={gain:.2f}dB",
                 "-ac", "1", "-ar", "44100", "-c:a", "libmp3lame", "-q:a", "4", str(dst)])
            over = true_peak(dst) + 1.0
            if over <= 0:
                break
            gain -= over + 0.1
        cut.unlink()


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    if sys.argv[1:] in (["confetti"], ["roar"], ["zippy"]):
        {"confetti": confetti, "roar": roar, "zippy": zippy}[sys.argv[1]]()
        sys.exit(0)
    t = snores()
    laugh()
    alarm()
    confetti()
    roar()
    zippy()
    print("snores:", json.dumps(t))
    sys.exit(0)
